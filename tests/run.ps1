# Builds and runs the patch's tests (see tests\README.md). Exit code 0 when every test passes.
#   tests\run.ps1                 all tests
#   tests\run.ps1 -Filter pak     only tests whose name contains "pak"
#   tests\run.ps1 -GameExe "D:\L2HD-test\Lords of the Realm II\Lords2.exe"
#                                 also the hook tests on a copy of the game's exe (or set L2HD_GAME_EXE); it is
#                                 only read, never changed, and nothing of it goes into the repository
# Needs the same compiler as hd\build.ps1 (llvm-mingw, 32-bit). Output goes to tests\out (not in git).
param([string]$Filter = "", [string]$GameExe = $env:L2HD_GAME_EXE)
$ErrorActionPreference = 'Stop'
$c = & "$PSScriptRoot\..\tools\find_cc.ps1"
$cc = $c.cc; $target = $c.args
$out = Join-Path $PSScriptRoot "out"
New-Item -ItemType Directory -Force $out | Out-Null
$env:L2HD_GAME_EXE = $GameExe

# Every trampoline variable of the patch (o_*), for the hook tests: which are still NULL after install()
$src = Get-Content "$PSScriptRoot\..\hd\lords2hd.c" -Raw
$ids = [regex]::Matches($src, '\bo_[A-Za-z0-9_]+\b') | ForEach-Object Value | Sort-Object -Unique
$lines = @("/* generated by tests\run.ps1 from hd\lords2hd.c: the patch's trampolines */",
    "static const struct { const char *name; void **p; int n; } t_tramps[] = {")
$lines += $ids | ForEach-Object { "`t{ `"$_`", (void **)&$_, (int)(sizeof $_ / sizeof(void *)) }," }
$lines += "};"
Set-Content "$out\tramps.h" -Value $lines -Encoding ascii

function Build-Part($what, [string[]]$ccArgs) {
    & $cc @target @ccArgs
    if ($LASTEXITCODE -ne 0) { throw "tests: building $what failed" }
}
# The host owns the game's address range: linked just below the game's image base, never moved.
Build-Part "the host" @('-O2', '-Wall', '-o', "$out\l2hd_tests.exe", "$PSScriptRoot\host.c",
    '-Wl,--image-base,0x300000', '-Wl,--disable-dynamicbase')
# The packer, as tools\make_pak.ps1 builds it (the pack tests run it).
Build-Part "l2pak" @('-O2', '-Wall', '-o', "$out\l2pak.exe", "$PSScriptRoot\..\tools\l2pak.c")
# The patch's source with the tests, at the release build's optimisation.
Build-Part "the tests" @('-O2', '-Wall', '-Wno-unused-function', '-shared', '-o', "$out\l2hd_tests.dll", "$PSScriptRoot\tests.c",
    '-luser32', '-lgdi32', '-lwinmm', '-lole32', '-lmfuuid', '-lwindowscodecs', '-luuid', '-lshell32')

$t0 = Get-Date
& "$out\l2hd_tests.exe" $Filter
$code = $LASTEXITCODE
"tests: {0:N1} s, exit {1}" -f ((Get-Date) - $t0).TotalSeconds, $code
exit $code
